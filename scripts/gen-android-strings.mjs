// Generate the Android string resources from the web app's i18n dictionaries.
//
// src/i18n/es.ts is the canonical shape; en.ts mirrors it. Rather than keeping a
// second, hand-written copy of every string for Android — which would drift the
// moment someone edits one and forgets the other — the Android resources are
// generated from those same files.
//
//   npm run gen:android-strings
//
// Run it whenever src/i18n/* changes, and commit the result. The nested keys are
// flattened with underscores: nav.dashboard -> R.string.nav_dashboard.

import { build } from "esbuild";
import { mkdir, writeFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const OUT = {
  es: "android/app/src/main/res/values/strings_i18n.xml",
  en: "android/app/src/main/res/values-en/strings_i18n.xml",
};

// The in-app changelog is the same content in both apps, so it ships to Android
// as a generated asset rather than a second hand-kept copy.
const CHANGELOG_OUT = "android/app/src/main/assets/changelog.json";

// System seed rows (categories, currencies) are stored in D1 with Spanish names,
// so translating them is a lookup on the stored value rather than a string
// resource. Same table as the web's `seedName`, generated for the same reason.
const SEED_OUT = "android/app/src/main/java/com/asura/finanzas/ui/SeedNames.kt";

// `default`, `object`, … are Java keywords; R.string.default would not compile.
const JAVA_KEYWORDS = new Set([
  "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char",
  "class", "const", "continue", "default", "do", "double", "else", "enum",
  "extends", "final", "finally", "float", "for", "goto", "if", "implements",
  "import", "instanceof", "int", "interface", "long", "native", "new", "package",
  "private", "protected", "public", "return", "short", "static", "strictfp",
  "super", "switch", "synchronized", "this", "throw", "throws", "transient",
  "try", "void", "volatile", "while",
]);

function keyFor(path) {
  const name = path
    .map((part) => part.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase())
    .join("_")
    .replace(/[^a-z0-9_]/g, "_");
  return JAVA_KEYWORDS.has(name) ? `${name}_` : name;
}

function flatten(node, path, out) {
  for (const [key, value] of Object.entries(node)) {
    const next = [...path, key];
    if (typeof value === "string") out.set(keyFor(next), value);
    else if (value && typeof value === "object") flatten(value, next, out);
  }
}

// Android string resources are XML with a handful of extra escapes of their own.
function escape(value) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n");
}

function toXml(entries, locale) {
  const rows = [...entries]
    .map(([name, value]) => {
      // A bare % is a format specifier to aapt unless the string opts out.
      const formatted = value.includes("%") ? ' formatted="false"' : "";
      return `    <string name="${name}"${formatted}>${escape(value)}</string>`;
    })
    .join("\n");

  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by scripts/gen-android-strings.mjs from src/i18n/${locale}.ts — do not edit.
  Add or change strings in src/i18n/, then run: npm run gen:android-strings
-->
<resources>
${rows}
</resources>
`;
}

async function loadDictionaries() {
  // The dictionaries are TypeScript and import each other, so bundle them into
  // one plain module node can import. store.ts touches localStorage/navigator at
  // module scope, but both accesses are already guarded, so it is safe here.
  //
  // The bundle lands inside the project (not /tmp) so its `react` import still
  // resolves against node_modules.
  const cacheDir = join("node_modules", ".cache");
  await mkdir(cacheDir, { recursive: true });

  async function load(entry, exportName) {
    const tmp = join(cacheDir, `broke-i18n-${exportName}-${Date.now()}.mjs`);
    await build({
      entryPoints: [entry],
      bundle: true,
      format: "esm",
      platform: "node",
      outfile: tmp,
      external: ["react"],
      logLevel: "silent",
    });
    const module = await import(pathToFileURL(tmp).href);
    await rm(tmp, { force: true });
    return module[exportName] ?? null;
  }

  return {
    es: await load("src/i18n/es.ts", "esDict"),
    en: await load("src/i18n/en.ts", "en"),
    changelog: await load("src/lib/changelog.ts", "changelog"),
    seed: await load("src/i18n/seed.ts", "EN"),
  };
}

/** Kotlin string literal: only backslash and quote need escaping here. */
function kotlinString(value) {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;
}

function toSeedKotlin(seed) {
  const rows = Object.entries(seed)
    .map(([es, en]) => `    ${kotlinString(es)} to ${kotlinString(en)},`)
    .join("\n");

  return `package com.asura.finanzas.ui

// GENERATED by scripts/gen-android-strings.mjs from src/i18n/seed.ts — do not edit.
// Add or change entries in src/i18n/seed.ts, then run: npm run gen:android-strings

import androidx.compose.runtime.Composable

/** Canonical Spanish seed name -> English, mirroring the web's \`seedName\`. */
val SEED_EN: Map<String, String> = mapOf(
${rows}
)

/**
 * Localize the name of a system seed row. User-created rows (\`isSystem\` false)
 * and the Spanish locale return the stored name verbatim.
 */
fun seedName(name: String?, isSystem: Boolean, locale: String): String? {
    if (name == null || !isSystem || !locale.startsWith("en")) return name
    return SEED_EN[name] ?: name
}

/** Same, resolved against the language chosen in the app's own settings. */
@Composable
fun seedName(name: String?, isSystem: Boolean = true): String? =
    seedName(name, isSystem, LocalAppSettings.current.locale)
`;
}

async function main() {
  const { es, en, changelog, seed } = await loadDictionaries();

  if (seed) {
    await writeFile(SEED_OUT, toSeedKotlin(seed), "utf8");
    console.log(`${SEED_OUT} — ${Object.keys(seed).length} nombres semilla`);
  }

  if (changelog) {
    await mkdir(CHANGELOG_OUT.slice(0, CHANGELOG_OUT.lastIndexOf("/")), { recursive: true });
    await writeFile(CHANGELOG_OUT, JSON.stringify(changelog, null, 2) + "\n", "utf8");
    console.log(`${CHANGELOG_OUT} — ${changelog.length} versiones`);
  }
  if (!es) throw new Error("src/i18n/es.ts no exportó esDict");

  const dictionaries = { es, en };
  for (const [locale, dict] of Object.entries(dictionaries)) {
    if (!dict) {
      console.warn(`aviso: no se encontró el diccionario ${locale}, se omite`);
      continue;
    }
    const entries = new Map();
    flatten(dict, [], entries);
    const path = OUT[locale];
    await mkdir(path.slice(0, path.lastIndexOf("/")), { recursive: true });
    await writeFile(path, toXml(entries, locale), "utf8");
    console.log(`${path} — ${entries.size} cadenas`);
  }

  // A missing key on one side means a screen would fall back to Spanish without
  // anyone noticing, which is exactly the drift this script exists to prevent.
  const esKeys = new Map();
  const enKeys = new Map();
  flatten(es, [], esKeys);
  if (en) flatten(en, [], enKeys);
  const missing = [...esKeys.keys()].filter((k) => en && !enKeys.has(k));
  const extra = [...enKeys.keys()].filter((k) => !esKeys.has(k));
  if (missing.length || extra.length) {
    console.error("\nLos diccionarios no coinciden:");
    for (const k of missing) console.error(`  falta en en.ts: ${k}`);
    for (const k of extra) console.error(`  sobra en en.ts:  ${k}`);
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
